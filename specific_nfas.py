class SpecificNFA:
    def __init__(
        self,
        name: str,
        m: int,
        transitions: list[tuple[int, int, int]],
        start: list[int],
        accept: list[int],
    ):
        self.name = name
        self.m = m
        self.transitions = transitions
        self.start = start
        self.accept = accept

    def to_tuple(self) -> tuple[int, list[tuple[int, int, int]], list[int], list[int]]:
        return (self.m, self.transitions, self.start, self.accept)


